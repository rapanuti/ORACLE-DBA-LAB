# 2. Creación de tabla, 3. inserción ------------------------------------------
def test_crear_tabla_e_insertar(client):
    script = """
CREATE TABLE prueba_lab (
  id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_paciente NUMBER REFERENCES pacientes (id_paciente),
  nota    VARCHAR2(100) NOT NULL
);
INSERT INTO prueba_lab (id_paciente, nota) VALUES (1, 'Primera nota');
INSERT INTO prueba_lab (id_paciente, nota) VALUES (2, 'Segunda nota');
COMMIT;
SELECT COUNT(*) AS total FROM prueba_lab;
"""
    r = run(client, script)
    assert r.status_code == 200, r.text
    res = r.json()["results"]
    assert [x["status"] for x in res] == ["ok"] * 5
    assert res[0]["kind"] == "ddl"
    assert res[1]["rowcount"] == 1 and res[1]["message"] == "1 fila(s) insertada(s)"
    assert res[4]["rows"] == [[2]]
    assert r.json()["transaction_pending"] is False
    assert all(x["elapsed_ms"] >= 0 for x in res)


# 4. Consulta con JOIN ---------------------------------------------------------
def test_consulta_join(client):
    r = run(client, """
SELECT pl.nota, p.nombres || ' ' || p.apellidos AS paciente, COUNT(c.id_cita) AS citas
FROM prueba_lab pl
JOIN pacientes p ON p.id_paciente = pl.id_paciente
LEFT JOIN citas c ON c.id_paciente = p.id_paciente
GROUP BY pl.nota, p.nombres, p.apellidos
ORDER BY pl.nota""")
    res = r.json()["results"][0]
    assert res["status"] == "ok", res
    assert [c["name"] for c in res["columns"]] == ["NOTA", "PACIENTE", "CITAS"]
    assert len(res["rows"]) == 2 and res["rows"][0][0] == "Primera nota"
    assert all(isinstance(row[2], int) for row in res["rows"])


# 5. Función PL/SQL ------------------------------------------------------------
def test_funcion_plsql_y_dbms_output(client):
    script = """
CREATE OR REPLACE FUNCTION fn_notas_paciente (p_id IN NUMBER) RETURN NUMBER IS
  v_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_n FROM prueba_lab WHERE id_paciente = p_id;
  RETURN v_n;
END;
/
SELECT fn_notas_paciente(1) AS n FROM dual;
DECLARE
  v_nac DATE;
BEGIN
  SELECT fecha_nacimiento INTO v_nac FROM pacientes WHERE id_paciente = 1;
  DBMS_OUTPUT.PUT_LINE('Notas del paciente 1: ' || fn_notas_paciente(1));
  DBMS_OUTPUT.PUT_LINE('Edad paciente 1: ' || fn_edad(v_nac));
END;
/
"""
    r = run(client, script)
    res = r.json()["results"]
    assert [x["status"] for x in res] == ["ok", "ok", "ok"], res
    assert res[0]["kind"] == "ddl" and "FUNCTION FN_NOTAS_PACIENTE" in res[0]["message"].upper()
    assert res[1]["rows"] == [[1]]
    assert res[2]["dbms_output"][0] == "Notas del paciente 1: 1"
    assert res[2]["dbms_output"][1].startswith("Edad paciente 1: ")


