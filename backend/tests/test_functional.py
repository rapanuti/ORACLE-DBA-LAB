def test_destructivo_requiere_confirmacion(client):
    r = run(client, "DELETE FROM prueba_lab")
    assert r.status_code == 409 and r.json()["error"] == "confirmation_required"
    assert run(client, "SELECT COUNT(*) FROM prueba_lab").json()["results"][0]["rows"] == [[2]]
    r = run(client, "DROP TABLE prueba_lab PURGE")
    assert r.status_code == 409
    r = run(client, "DROP FUNCTION fn_notas_paciente;\nDROP PROCEDURE pr_roto;\nDROP TABLE prueba_lab PURGE", confirm=True)
    assert r.status_code == 200 and all(x["status"] == "ok" for x in r.json()["results"])


