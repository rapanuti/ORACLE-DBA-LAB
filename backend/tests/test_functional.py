def test_solo_lectura_bloquea_escrituras(client, monkeypatch):
    """Simula un perfil remoto de solo lectura apuntando a la base local."""
    from app import db
    from app.executor import PolicyError, execute_script
    lab = db.get_profile("lab")
    ro = db.Profile("external", "remoto (prueba)", "external", False, lab.dsn, lab.user, lab.password)
    sess = db.SqlSession("pytest-ro", ro)
    try:
        with pytest.raises(PolicyError) as exc:
            execute_script(sess, "SELECT 1 FROM dual; INSERT INTO roles (nombre) VALUES ('X')")
        assert exc.value.status == 403
        res = execute_script(sess, "SELECT COUNT(*) FROM roles").results[0]
        assert res["status"] == "ok" and res["rows"] == [[4]]
    finally:
        sess.close()


