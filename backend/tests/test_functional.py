# Transacciones -----------------------------------------------------------------
def test_commit_rollback(client):
    r = run(client, "UPDATE prueba_lab SET nota = 'cambiada' WHERE id_paciente = 1")
    assert r.json()["transaction_pending"] is True
    # Otra sesión no ve el cambio sin COMMIT
    other = run(client, "SELECT nota FROM prueba_lab WHERE id_paciente = 1", sid="pytest-otra")
    assert other.json()["results"][0]["rows"] == [["Primera nota"]]
    r = run(client, "ROLLBACK")
    assert r.json()["transaction_pending"] is False
    r = run(client, "SELECT nota FROM prueba_lab WHERE id_paciente = 1")
    assert r.json()["results"][0]["rows"] == [["Primera nota"]]
    client.delete("/api/sql/session/pytest-otra")


