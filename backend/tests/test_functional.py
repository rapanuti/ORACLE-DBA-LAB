@pytest.mark.parametrize("ex_id", [e["id"] for e in exercises.EXERCISES])
def test_solucion_de_ejercicio_valida(client, ex_id):
    ex = exercises.BY_ID[ex_id]
    sid = "pytest-ex"
    if ex.get("cleanup"):
        client.post(f"/api/exercises/{ex_id}/cleanup", json={"session_id": sid, "sql": ""})
    r = client.post(f"/api/exercises/{ex_id}/run", json={"session_id": sid, "sql": ex["solution"]})
