from app.sql_parser import classify, split_sql
from app.pg_compare import translate


def test_split_simple_statements():
    stmts = split_sql("SELECT 1 FROM dual;\nSELECT 'a;b' FROM dual;\n-- comentario ;\nSELECT 2 FROM dual")
    assert [s.text for s in stmts] == ["SELECT 1 FROM dual", "SELECT 'a;b' FROM dual", "SELECT 2 FROM dual"]
    assert [s.start_line for s in stmts] == [1, 2, 4]


def test_split_plsql_blocks():
    script = """CREATE TABLE t (a NUMBER);
CREATE OR REPLACE FUNCTION f RETURN NUMBER IS
BEGIN
  RETURN 1; -- ; dentro de PL/SQL
END;
/
BEGIN
  DBMS_OUTPUT.PUT_LINE('x;y');
END;
/
SELECT f FROM dual;"""
    stmts = split_sql(script)
    assert len(stmts) == 4
    assert stmts[1].is_plsql and stmts[1].text.endswith("END;")
    assert stmts[2].text.startswith("BEGIN") and stmts[2].start_line == 7
    assert stmts[3].text == "SELECT f FROM dual"


def test_split_plsql_without_slash_at_end():
    stmts = split_sql("BEGIN NULL; END;")
    assert len(stmts) == 1 and stmts[0].text == "BEGIN NULL; END;"


def test_q_quote_and_block_comments():
    stmts = split_sql("SELECT q'[it's; ok]' FROM dual; /* ; */ SELECT 1 FROM dual;")
    assert len(stmts) == 2


def test_classify_destructive():
    assert classify("DROP TABLE x").destructive
    assert classify("TRUNCATE TABLE x").destructive
    assert classify("DELETE FROM citas").destructive
    assert not classify("DELETE FROM citas WHERE id_cita = 1").destructive
    assert classify("UPDATE citas SET estado = 'X'").destructive
    assert not classify("UPDATE citas SET motivo = 'where' WHERE id_cita = 1").destructive
    assert classify("UPDATE citas SET motivo = 'where'").destructive  # 'where' en cadena no cuenta
    assert classify("ALTER TABLE t DROP COLUMN c").destructive
    assert classify("BEGIN EXECUTE IMMEDIATE 'DROP TABLE t'; END;").kind == "plsql"
    assert classify("SELECT * FROM t").kind == "query"
    assert classify("  -- hola\n WITH x AS (SELECT 1 FROM dual) SELECT * FROM x").kind == "query"
    assert classify("CREATE OR REPLACE PACKAGE BODY pkg AS END;").plsql_object == ("PACKAGE BODY", "PKG")


def test_pg_translate():
    out = translate("SELECT nombre FROM t WHERE nombre ILIKE 'a%' ORDER BY 1 LIMIT 5;")
    assert "UPPER(nombre) LIKE UPPER('a%')" in out["oracle_sql"]
    assert "FETCH FIRST 5 ROWS ONLY" in out["oracle_sql"]
    out = translate("CREATE TABLE n (id SERIAL PRIMARY KEY, t TEXT);")
    assert "GENERATED BY DEFAULT AS IDENTITY" in out["oracle_sql"] and "CLOB" in out["oracle_sql"]
    assert translate("SELECT NOW();")["oracle_sql"] == "SELECT SYSTIMESTAMP FROM dual;"
