"""Creación y restauración del esquema educativo.

Protecciones:
  * Solo opera con el perfil "lab" y verifica que el usuario conectado sea LAB_DB_USER.
  * La restauración solo borra objetos si el esquema está vacío o contiene la tabla
    marcadora LAB_METADATA creada por este seeder (evita borrar esquemas ajenos).
"""
from __future__ import annotations

import datetime as dt
import logging
import time
from pathlib import Path

import oracledb

from ..config import get_settings
from ..db import connect, get_profile
from ..sql_parser import split_sql
from .data import IDENTITY_TABLES, INSERTS, generate

log = logging.getLogger("seed")
SCHEMA_FILE = Path(__file__).with_name("schema.sql")
SCHEMA_VERSION = "1.0"

ID_COLUMNS = {
    "roles": "id_rol", "especialidades": "id_especialidad", "usuarios": "id_usuario",
    "medicos": "id_medico", "consultorios": "id_consultorio", "pacientes": "id_paciente",
    "citas": "id_cita", "historias_clinicas": "id_historia", "pagos": "id_pago",
}
DROP_ORDER = ["TRIGGER", "VIEW", "MATERIALIZED VIEW", "PACKAGE", "PROCEDURE", "FUNCTION",
              "SYNONYM", "TABLE", "SEQUENCE", "TYPE"]


class SeedError(Exception):
    pass


def _lab_connection() -> oracledb.Connection:
    profile = get_profile("lab")
    conn = connect(profile)
    conn.call_timeout = 0
    cur = conn.cursor()
    cur.execute("SELECT SYS_CONTEXT('USERENV','CURRENT_USER') FROM dual")
    current = cur.fetchone()[0]
    if current.upper() != get_settings().lab_db_user.upper():
        conn.close()
        raise SeedError(f"Conectado como {current}, se esperaba {get_settings().lab_db_user.upper()}. Operación cancelada.")
    return conn


def schema_status(conn: oracledb.Connection | None = None) -> dict:
    own = conn is None
    conn = conn or _lab_connection()
    try:
        cur = conn.cursor()
        cur.execute("SELECT object_type, COUNT(*) FROM user_objects WHERE object_name NOT LIKE 'BIN$%' GROUP BY object_type")
        counts = {r[0]: r[1] for r in cur}
        cur.execute("SELECT COUNT(*) FROM user_tables WHERE table_name = 'LAB_METADATA'")
        has_marker = cur.fetchone()[0] == 1
        meta = {}
        if has_marker:
            cur.execute("SELECT clave, valor FROM lab_metadata")
            meta = dict(cur.fetchall())
        return {"objects": counts, "seeded": has_marker, "metadata": meta,
                "empty": sum(counts.values()) == 0}
    finally:
        if own:
            conn.close()


def _drop_all(conn: oracledb.Connection) -> int:
    cur = conn.cursor()
    dropped = 0
    for otype in DROP_ORDER:
        cur.execute("""SELECT object_name FROM user_objects
                       WHERE object_type = :t AND object_name NOT LIKE 'BIN$%'
                         AND object_name NOT LIKE 'ISEQ$$%'""", t=otype)
        for (name,) in cur.fetchall():
            extra = " CASCADE CONSTRAINTS PURGE" if otype == "TABLE" else (" FORCE" if otype == "TYPE" else "")
            try:
                cur.execute(f'DROP {otype} "{name}"{extra}')
                dropped += 1
            except oracledb.DatabaseError as exc:
                log.warning("No se pudo eliminar %s %s: %s", otype, name, exc)
    cur.execute("PURGE RECYCLEBIN")
    return dropped


def create_schema(conn: oracledb.Connection, today: dt.date | None = None) -> dict:
    cur = conn.cursor()
    for stmt in split_sql(SCHEMA_FILE.read_text(encoding="utf-8")):
        cur.execute(stmt.text)
    cur.execute("""SELECT name, type, line, text FROM user_errors ORDER BY name, sequence""")
    errors = cur.fetchall()
    if errors:
        raise SeedError(f"Errores de compilación en el esquema: {errors}")

    data = generate(today)
    counts = {}
    for table, sql in INSERTS.items():
        rows = data[table]
        cur.executemany(sql, rows)
        counts[table] = len(rows)
    for table in IDENTITY_TABLES:
        cur.execute(f"ALTER TABLE {table} MODIFY {ID_COLUMNS[table]} "
                    "GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)")
    cur.execute(f"ALTER SEQUENCE seq_factura RESTART START WITH {data['_next_factura'][0][0]}")
    cur.executemany("INSERT INTO lab_metadata (clave, valor) VALUES (:1, :2)", [
        ("schema", "citas_medicas"), ("version", SCHEMA_VERSION),
        ("creado", dt.datetime.now().isoformat(timespec="seconds")),
        ("aviso", "Datos ficticios con fines educativos"),
    ])
    conn.commit()
    # El ALTER ... IDENTITY invalida las vistas dependientes: recompilar lo inválido.
    cur.execute("BEGIN DBMS_UTILITY.COMPILE_SCHEMA(schema => USER, compile_all => FALSE); END;")
    for table in INSERTS:
        cur.callproc("dbms_stats.gather_table_stats", [None, table.upper()])
    return counts


def reset_schema() -> dict:
    s = get_settings()
    if not s.lab_allow_reset:
        raise SeedError("La restauración está deshabilitada (LAB_ALLOW_RESET=false).")
    t0 = time.perf_counter()
    conn = _lab_connection()
    try:
        status = schema_status(conn)
        if not status["empty"] and not status["seeded"]:
            raise SeedError(
                "El esquema contiene objetos pero NO tiene la marca LAB_METADATA del laboratorio. "
                "Por seguridad no se borrará nada. Usa un esquema dedicado y vacío.")
        dropped = _drop_all(conn)
        counts = create_schema(conn)
        return {"dropped": dropped, "rows": counts,
                "elapsed_ms": round((time.perf_counter() - t0) * 1000, 1)}
    finally:
        conn.close()


def ensure_seeded() -> dict | None:
    """Crea el esquema si está vacío (arranque automático)."""
    conn = _lab_connection()
    try:
        status = schema_status(conn)
        if status["empty"]:
            log.info("Esquema vacío: creando esquema educativo de citas médicas...")
            return {"rows": create_schema(conn)}
        return None
    finally:
        conn.close()
