COMMENT ON TABLE citas IS 'Agenda de citas médicas. Una cita por médico y hora.';
COMMENT ON COLUMN citas.estado IS 'PROGRAMADA, CONFIRMADA, ATENDIDA, CANCELADA o NO_ASISTIO';
COMMENT ON TABLE pacientes IS 'Pacientes ficticios registrados en la clínica.';
COMMENT ON TABLE pagos IS 'Pagos asociados a citas. numero_factura usa SEQ_FACTURA.';

-- ------------------------------------------------------------ vistas
CREATE OR REPLACE VIEW v_citas_detalle AS
SELECT c.id_cita,
       c.fecha_hora,
       c.estado,
       c.motivo,
       p.id_paciente,
       p.nombres || ' ' || p.apellidos  AS paciente,
       m.id_medico,
       m.nombres || ' ' || m.apellidos  AS medico,
       e.nombre                          AS especialidad,
       co.codigo                         AS consultorio
FROM   citas c
JOIN   pacientes p       ON p.id_paciente = c.id_paciente
JOIN   medicos m         ON m.id_medico = c.id_medico
JOIN   especialidades e  ON e.id_especialidad = m.id_especialidad
JOIN   consultorios co   ON co.id_consultorio = c.id_consultorio;

CREATE OR REPLACE VIEW v_ingresos_especialidad AS
SELECT e.nombre AS especialidad,
       COUNT(pg.id_pago) AS pagos,
       SUM(pg.monto)     AS total
FROM   pagos pg
JOIN   citas c          ON c.id_cita = pg.id_cita
JOIN   medicos m        ON m.id_medico = c.id_medico
JOIN   especialidades e ON e.id_especialidad = m.id_especialidad
WHERE  pg.estado = 'PAGADO'
GROUP  BY e.nombre;

-- ------------------------------------------------------------ PL/SQL
CREATE OR REPLACE FUNCTION fn_edad (p_fecha_nacimiento IN DATE) RETURN NUMBER
IS
BEGIN
  RETURN TRUNC(MONTHS_BETWEEN(SYSDATE, p_fecha_nacimiento) / 12);
END fn_edad;
/

CREATE OR REPLACE FUNCTION fn_total_pagado_paciente (p_id_paciente IN NUMBER) RETURN NUMBER
IS
  v_total NUMBER;
BEGIN
  SELECT NVL(SUM(pg.monto), 0)
    INTO v_total
    FROM pagos pg
    JOIN citas c ON c.id_cita = pg.id_cita
   WHERE c.id_paciente = p_id_paciente
     AND pg.estado = 'PAGADO';
  RETURN v_total;
END fn_total_pagado_paciente;
/

CREATE OR REPLACE PROCEDURE pr_registrar_pago (
  p_id_cita  IN  NUMBER,
  p_monto    IN  NUMBER,
  p_metodo   IN  VARCHAR2,
  p_id_pago  OUT NUMBER
) IS
  v_estado citas.estado%TYPE;
BEGIN
  SELECT estado INTO v_estado FROM citas WHERE id_cita = p_id_cita;
  IF v_estado = 'CANCELADA' THEN
    RAISE_APPLICATION_ERROR(-20002, 'No se puede cobrar una cita cancelada');
  END IF;
  INSERT INTO pagos (id_cita, monto, metodo, estado, fecha_pago, numero_factura)
  VALUES (p_id_cita, p_monto, p_metodo, 'PAGADO', SYSDATE, 'F-' || seq_factura.NEXTVAL)
  RETURNING id_pago INTO p_id_pago;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'La cita ' || p_id_cita || ' no existe');
END pr_registrar_pago;
/

CREATE OR REPLACE PACKAGE pkg_citas AS
  FUNCTION medico_disponible (p_id_medico IN NUMBER, p_fecha_hora IN TIMESTAMP) RETURN NUMBER;
  PROCEDURE agendar (p_id_paciente IN NUMBER, p_id_medico IN NUMBER, p_id_consultorio IN NUMBER,
                     p_fecha_hora IN TIMESTAMP, p_motivo IN VARCHAR2, p_id_cita OUT NUMBER);
  PROCEDURE cancelar (p_id_cita IN NUMBER);
  FUNCTION citas_del_dia (p_fecha IN DATE DEFAULT TRUNC(SYSDATE)) RETURN NUMBER;
  PROCEDURE resumen_medico (p_id_medico IN NUMBER);
END pkg_citas;
/

CREATE OR REPLACE PACKAGE BODY pkg_citas AS
  FUNCTION medico_disponible (p_id_medico IN NUMBER, p_fecha_hora IN TIMESTAMP) RETURN NUMBER IS
    v_n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_n FROM citas
     WHERE id_medico = p_id_medico AND fecha_hora = p_fecha_hora
       AND estado NOT IN ('CANCELADA');
    RETURN CASE WHEN v_n = 0 THEN 1 ELSE 0 END;
  END;

  PROCEDURE agendar (p_id_paciente IN NUMBER, p_id_medico IN NUMBER, p_id_consultorio IN NUMBER,
                     p_fecha_hora IN TIMESTAMP, p_motivo IN VARCHAR2, p_id_cita OUT NUMBER) IS
  BEGIN
    IF p_fecha_hora < SYSTIMESTAMP THEN
      RAISE_APPLICATION_ERROR(-20003, 'No se pueden agendar citas en el pasado');
    END IF;
    IF medico_disponible(p_id_medico, p_fecha_hora) = 0 THEN
      RAISE_APPLICATION_ERROR(-20004, 'El médico ya tiene una cita a esa hora');
    END IF;
    INSERT INTO citas (id_paciente, id_medico, id_consultorio, fecha_hora, motivo, estado)
    VALUES (p_id_paciente, p_id_medico, p_id_consultorio, p_fecha_hora, p_motivo, 'PROGRAMADA')
    RETURNING id_cita INTO p_id_cita;
  END;

  PROCEDURE cancelar (p_id_cita IN NUMBER) IS
  BEGIN
    UPDATE citas SET estado = 'CANCELADA'
     WHERE id_cita = p_id_cita AND estado IN ('PROGRAMADA','CONFIRMADA');
    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20005, 'La cita no existe o no se puede cancelar');
    END IF;
  END;

  FUNCTION citas_del_dia (p_fecha IN DATE DEFAULT TRUNC(SYSDATE)) RETURN NUMBER IS
    v_n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_n FROM citas
     WHERE fecha_hora >= TRUNC(p_fecha) AND fecha_hora < TRUNC(p_fecha) + 1;
    RETURN v_n;
  END;

  PROCEDURE resumen_medico (p_id_medico IN NUMBER) IS
  BEGIN
    FOR r IN (SELECT estado, COUNT(*) AS n FROM citas
               WHERE id_medico = p_id_medico GROUP BY estado ORDER BY estado) LOOP
      DBMS_OUTPUT.PUT_LINE(RPAD(r.estado, 12) || ': ' || r.n);
    END LOOP;
  END;
END pkg_citas;
/

CREATE OR REPLACE TRIGGER trg_citas_bu
BEFORE UPDATE ON citas
FOR EACH ROW
BEGIN
  :NEW.fecha_actualizacion := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_citas_auditoria
AFTER UPDATE OF estado ON citas
FOR EACH ROW
WHEN (NEW.estado <> OLD.estado)
BEGIN
  INSERT INTO citas_auditoria (id_cita, estado_anterior, estado_nuevo)
  VALUES (:OLD.id_cita, :OLD.estado, :NEW.estado);
END;
/
