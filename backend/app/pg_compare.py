"""Traductor aproximado PostgreSQL -> Oracle con notas didácticas.

No es un traductor completo: aplica reglas por expresiones regulares y explica cada
cambio. Siempre revisa el resultado antes de ejecutarlo.
"""
from __future__ import annotations

import re
from typing import Callable

Rule = tuple[str, str, re.Pattern, "str | Callable[[re.Match], str]", str]

CAST_TYPES = {"text": "VARCHAR2(4000)", "varchar": "VARCHAR2(4000)", "int": "NUMBER",
              "integer": "NUMBER", "bigint": "NUMBER", "numeric": "NUMBER", "date": "DATE",
              "timestamp": "TIMESTAMP", "float": "BINARY_DOUBLE", "boolean": "BOOLEAN"}
TRUNC_UNITS = {"year": "YYYY", "quarter": "Q", "month": "MM", "week": "IW", "day": "DD",
               "hour": "HH24", "minute": "MI"}


def _cast(m: re.Match) -> str:
    t = m.group(2).lower()
    return f"CAST({m.group(1)} AS {CAST_TYPES.get(t, t.upper())})"


def _date_trunc(m: re.Match) -> str:
    unit = TRUNC_UNITS.get(m.group(1).lower(), m.group(1).upper())
    return f"TRUNC({m.group(2)}, '{unit}')"


def _limit_offset(m: re.Match) -> str:
    return f"OFFSET {m.group(2)} ROWS FETCH NEXT {m.group(1)} ROWS ONLY"


def _offset_limit(m: re.Match) -> str:
    return f"OFFSET {m.group(1)} ROWS FETCH NEXT {m.group(2)} ROWS ONLY"


def _gen_series(m: re.Match) -> str:
    a, b = int(m.group(1)), int(m.group(2))
    return f"(SELECT LEVEL + {a - 1} AS generate_series FROM dual CONNECT BY LEVEL <= {b - a + 1})"


I = re.IGNORECASE
RULES: list[Rule] = [
    ("serial", "SERIAL → IDENTITY",
     re.compile(r"\b(BIG)?SERIAL\b", I), "NUMBER GENERATED BY DEFAULT AS IDENTITY",
     "PostgreSQL SERIAL crea una secuencia implícita. Oracle 12c+ usa columnas IDENTITY "
     "(o una SEQUENCE + DEFAULT seq.NEXTVAL)."),
    ("varchar", "VARCHAR(n) → VARCHAR2(n)",
     re.compile(r"\bVARCHAR\s*\(", I), "VARCHAR2(",
     "Oracle recomienda VARCHAR2. Máximo 4000 bytes (32767 con MAX_STRING_SIZE=EXTENDED)."),
    ("text", "TEXT → CLOB",
     re.compile(r"(?<!::)\bTEXT\b(?=\s*(,|\)|NOT|NULL|DEFAULT|$))", I), "CLOB",
     "Oracle no tiene TEXT. Usa VARCHAR2(4000) para textos cortos o CLOB para largos."),
    ("bytea", "BYTEA → BLOB", re.compile(r"\bBYTEA\b", I), "BLOB", "Datos binarios: BLOB (o RAW(n) si es pequeño)."),
    ("timestamptz", "TIMESTAMPTZ → TIMESTAMP WITH TIME ZONE",
     re.compile(r"\bTIMESTAMPTZ\b", I), "TIMESTAMP WITH TIME ZONE", "Mismo concepto, distinto nombre."),
    ("double", "DOUBLE PRECISION → BINARY_DOUBLE",
     re.compile(r"\bDOUBLE\s+PRECISION\b", I), "BINARY_DOUBLE",
     "Oracle acepta DOUBLE PRECISION (como NUMBER) pero BINARY_DOUBLE es el IEEE-754 nativo."),
    ("numeric", "NUMERIC → NUMBER", re.compile(r"\bNUMERIC\b", I), "NUMBER", "NUMBER(p,s) es el tipo numérico nativo de Oracle."),
    ("cast", "valor::tipo → CAST(valor AS tipo)",
     re.compile(r"('[^']*'|[\w.]+)::(\w+)", I), _cast,
     "El operador :: no existe en Oracle; usa CAST o funciones TO_NUMBER / TO_DATE / TO_CHAR."),
    ("now", "NOW() → SYSTIMESTAMP", re.compile(r"\bNOW\s*\(\s*\)", I), "SYSTIMESTAMP",
     "SYSDATE (DATE, con hora) o SYSTIMESTAMP (TIMESTAMP WITH TIME ZONE). Ojo: usan la hora del servidor."),
    ("current_date", "CURRENT_DATE → TRUNC(SYSDATE)", re.compile(r"\bCURRENT_DATE\b", I), "TRUNC(SYSDATE)",
     "En Oracle CURRENT_DATE existe pero incluye la HORA de la sesión; TRUNC(SYSDATE) es la fecha sin hora."),
    ("ilike", "ILIKE → UPPER(...) LIKE UPPER(...)",
     re.compile(r"([\w.]+)\s+ILIKE\s+('[^']*')", I), r"UPPER(\1) LIKE UPPER(\2)",
     "Oracle no tiene ILIKE. Alternativas: UPPER() en ambos lados o REGEXP_LIKE(col, patrón, 'i')."),
    ("date_trunc", "DATE_TRUNC → TRUNC(fecha, formato)",
     re.compile(r"DATE_TRUNC\s*\(\s*'(\w+)'\s*,\s*([^)]+)\)", I), _date_trunc,
     "TRUNC(fecha, 'MM') trunca al mes, 'YYYY' al año, 'IW' a la semana ISO."),
    ("string_agg", "STRING_AGG → LISTAGG ... WITHIN GROUP",
     re.compile(r"STRING_AGG\s*\(\s*([^,]+?)\s*,\s*('[^']*')\s*\)", I),
     r"LISTAGG(\1, \2) WITHIN GROUP (ORDER BY \1)",
     "LISTAGG requiere WITHIN GROUP (ORDER BY ...). Su resultado está limitado a VARCHAR2 (usa ON OVERFLOW TRUNCATE)."),
    ("nextval", "nextval('seq') → seq.NEXTVAL",
     re.compile(r"nextval\s*\(\s*'([\w.]+)'(::regclass)?\s*\)", I), r"\1.NEXTVAL",
     "En Oracle las secuencias se usan como pseudocolumnas: seq.NEXTVAL y seq.CURRVAL."),
    ("gen_series", "generate_series → CONNECT BY LEVEL",
     re.compile(r"generate_series\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)", I), _gen_series,
     "Oracle genera series con CONNECT BY LEVEL o con un WITH recursivo."),
    ("limit_offset", "LIMIT n OFFSET m → OFFSET m ROWS FETCH NEXT n ROWS ONLY",
     re.compile(r"\bLIMIT\s+(\d+)\s+OFFSET\s+(\d+)", I), _limit_offset,
     "Sintaxis estándar SQL:2008 soportada desde Oracle 12c."),
    ("offset_limit", "OFFSET m LIMIT n → OFFSET m ROWS FETCH NEXT n ROWS ONLY",
     re.compile(r"\bOFFSET\s+(\d+)\s+LIMIT\s+(\d+)", I), _offset_limit, "Igual que la anterior."),
    ("limit", "LIMIT n → FETCH FIRST n ROWS ONLY",
     re.compile(r"\bLIMIT\s+(\d+)", I), r"FETCH FIRST \1 ROWS ONLY",
     "Antes de 12c se usaba WHERE ROWNUM <= n sobre una subconsulta ordenada."),
    ("except", "EXCEPT → MINUS", re.compile(r"\bEXCEPT\b(?!\s+ALL)", I), "MINUS",
     "Oracle usa MINUS (23ai también acepta EXCEPT)."),
    ("bool_lit", "TRUE/FALSE", re.compile(r"(?<![\w'])(TRUE|FALSE)(?![\w'])", I), lambda m: m.group(1).upper(),
     "Oracle 23ai soporta BOOLEAN en SQL. En 19c y anteriores usa NUMBER(1) o CHAR(1) ('S'/'N')."),
]

NOTES_ONLY: list[tuple[str, str, re.Pattern, str]] = [
    ("on_conflict", "INSERT ... ON CONFLICT", re.compile(r"\bON\s+CONFLICT\b", I),
     "Oracle no tiene ON CONFLICT: usa MERGE INTO destino USING (...) ON (...) WHEN MATCHED THEN UPDATE WHEN NOT MATCHED THEN INSERT."),
    ("returning", "RETURNING", re.compile(r"\bRETURNING\b", I),
     "En Oracle RETURNING ... INTO solo funciona en PL/SQL o con variables bind (no devuelve un result set)."),
    ("distinct_on", "DISTINCT ON", re.compile(r"\bDISTINCT\s+ON\b", I),
     "No existe en Oracle. Usa ROW_NUMBER() OVER (PARTITION BY ... ORDER BY ...) y filtra = 1."),
    ("if_not_exists", "IF NOT EXISTS", re.compile(r"\bIF\s+(NOT\s+)?EXISTS\b", I),
     "Soportado en Oracle 23ai. En versiones anteriores hay que capturar ORA-00955 / ORA-00942 en PL/SQL."),
    ("epoch", "EXTRACT(EPOCH ...)", re.compile(r"\bEPOCH\b", I),
     "No hay EPOCH: (CAST(ts AS DATE) - DATE '1970-01-01') * 86400."),
    ("age", "AGE()", re.compile(r"\bAGE\s*\(", I),
     "Usa MONTHS_BETWEEN(fecha1, fecha2) / 12 o NUMTOYMINTERVAL."),
    ("coalesce_empty", "Cadenas vacías", re.compile(r"''"),
     "¡En Oracle '' ES NULL! Comparar col = '' nunca es verdadero; usa col IS NULL."),
    ("concat", "Concatenación ||", re.compile(r"\|\|"),
     "En PostgreSQL 'a' || NULL = NULL; en Oracle 'a' || NULL = 'a' (NULL se trata como cadena vacía)."),
    ("bool_type", "Tipo BOOLEAN", re.compile(r"\bBOOLEAN\b", I),
     "BOOLEAN existe en SQL desde Oracle 23ai. En versiones anteriores solo en PL/SQL."),
    ("schema", "Esquemas", re.compile(r"\bCREATE\s+SCHEMA\b", I),
     "En Oracle un esquema ES un usuario: CREATE USER ... (CREATE SCHEMA solo agrupa sentencias)."),
]

GENERAL_NOTES = [
    {"title": "DDL transaccional", "text": "En PostgreSQL el DDL puede deshacerse con ROLLBACK. En Oracle cada sentencia DDL hace COMMIT implícito antes y después."},
    {"title": "Autocommit", "text": "psql trabaja en autocommit por defecto. En Oracle (y en este laboratorio) los cambios DML quedan pendientes hasta COMMIT o ROLLBACK."},
    {"title": "Cadena vacía = NULL", "text": "Oracle trata '' como NULL. Una columna NOT NULL no acepta ''."},
    {"title": "Mayúsculas en identificadores", "text": "PostgreSQL convierte identificadores sin comillas a minúsculas; Oracle a MAYÚSCULAS. \"Tabla\" con comillas es sensible a mayúsculas en ambos."},
    {"title": "FROM DUAL", "text": "Antes de 23ai, SELECT siempre necesita FROM; para expresiones se usa la tabla DUAL: SELECT SYSDATE FROM dual."},
    {"title": "Esquema = usuario", "text": "En Oracle cada usuario es un esquema. No hay \"bases de datos\" múltiples dentro de una PDB como en PostgreSQL."},
    {"title": "Secuencias e IDENTITY", "text": "SERIAL ≈ GENERATED BY DEFAULT AS IDENTITY. Las secuencias se consultan con seq.NEXTVAL / seq.CURRVAL."},
    {"title": "Funciones de texto", "text": "length → LENGTH, substring → SUBSTR, position → INSTR, string_agg → LISTAGG, concat_ws → no existe (usa ||)."},
    {"title": "Fechas", "text": "fecha + 1 suma un día en Oracle. INTERVAL '1' DAY también funciona. TO_CHAR(fecha, 'YYYY-MM-DD') para formatear."},
    {"title": "PL/pgSQL vs PL/SQL", "text": "PL/SQL usa CREATE OR REPLACE PROCEDURE ... IS ... BEGIN ... END; sin $$ ni LANGUAGE. Las funciones se terminan con '/' en scripts."},
]


def translate(pg_sql: str) -> dict:
    out = pg_sql
    applied = []
    for rid, title, pattern, repl, note in RULES:
        new, n = pattern.subn(repl, out)
        if n:
            applied.append({"id": rid, "title": title, "count": n, "note": note})
            out = new
    # SELECT sin FROM -> FROM dual (solo sentencias simples de una línea)
    statements = [s for s in re.split(r";\s*\n?", out) if s.strip()]
    fixed = []
    dual_added = 0
    for s in statements:
        if re.match(r"^\s*SELECT\b", s, I) and not re.search(r"\bFROM\b", s, I):
            s = s.rstrip() + " FROM dual"
            dual_added += 1
        fixed.append(s.strip())
    if dual_added:
        applied.append({"id": "dual", "title": "SELECT sin FROM → FROM dual", "count": dual_added,
                        "note": "Antes de Oracle 23ai toda consulta necesita FROM. DUAL es una tabla de una fila."})
    out = ";\n".join(fixed) + (";" if fixed else "")
    warnings = [{"id": rid, "title": title, "note": note}
                for rid, title, pattern, note in NOTES_ONLY if pattern.search(pg_sql)]
    return {"oracle_sql": out, "applied": applied, "warnings": warnings}


